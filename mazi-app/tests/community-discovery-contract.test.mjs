import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=(p)=>readFileSync(new URL(p,import.meta.url),"utf8");
const gateway=read("../supabase/functions/mazi-member-api/index.ts");
const marketplace=read("../app/marketplace/page.tsx");
const forum=read("../app/forum/page.tsx");
const thread=read("../app/forum/[id]/page.tsx");
const dashboard=read("../app/dashboard/page.tsx");
const get=(operation,nextOperation)=>{
 const start=gateway.indexOf('if(operation==="'+operation+'")');
 const end=gateway.indexOf('if(operation==="'+nextOperation+'")',start);
 assert.ok(start>0&&end>start);
 return gateway.slice(start,end);
};
test("marketplace filtering is scoped to verified approved members and server-side pagination",()=>{
 const start=gateway.indexOf('if(operation==="marketplace_list"||operation==="marketplace_my")');
 const end=gateway.indexOf('if(operation==="marketplace_create")',start);
 const x=gateway.slice(start,end);
 assert.ok(start>0&&end>start);
 assert.match(x,/await verifiedMember\(user\.id\)/);
 assert.match(x,/category.*!.*"goods"/);
 assert.match(x,/kind.*!.*"offer"/);
 assert.match(x,/search\.length>80/);
 assert.match(x,/page>99/);
 assert.match(x,/\.is\("hidden_at",null\)/);
 assert.match(x,/\.eq\("status","active"\)/);
 assert.match(x,/query\.ilike\("title"/);
 assert.match(x,/query\.range\(page\*24,page\*24\+24\)/);
 assert.match(x,/has_more:paged&&rows\.length>24/);
 assert.match(x,/communityVisible/);
 assert.match(marketplace,/method="get" action="\/marketplace"/);
 assert.match(marketplace,/has_more&&page<99/);
});
test("forum topics preserve unpaged dashboard contract and add bounded discovery",()=>{
 const x=get("forum_list","forum_create");
 assert.match(x,/await verifiedMember\(user\.id\)/);
 assert.match(x,/paged=input\.page!==undefined/);
 assert.match(x,/page<0\|\|page>99/);
 assert.match(x,/search\.length>80/);
 assert.match(x,/query\.eq\("category",category\)/);
 assert.match(x,/query\.ilike\("title"/);
 assert.match(x,/\.is\("hidden_at",null\)/);
 assert.match(x,/query\.range\(page\*24,page\*24\+24\)/);
 assert.match(x,/await query\.limit\(60\)/);
 assert.match(x,/communityVisible/);
 assert.match(forum,/method="get" action="\/forum"/);
 assert.match(forum,/result\.has_more&&page<99/);
 assert.match(dashboard,/maziMemberRequest<\{threads:MaziForumThread\[\]\}>\("forum_list"\)/);
});
test("forum replies page safely after member/thread visibility enforcement",()=>{
 const x=get("forum_thread","forum_reply");
 assert.match(x,/await verifiedMember\(user\.id\)/);
 assert.match(x,/!uuid\(threadId\)/);
 assert.match(x,/!Number\.isInteger\(page\)/);
 assert.match(x,/page>99/);
 assert.match(x,/\.eq\("id",threadId\)\.is\("hidden_at",null\)/);
 assert.ok(x.indexOf("if(!visible.length)")<x.indexOf('admin.from("mazi_forum_replies")'));
 assert.match(x,/\.eq\("thread_id",threadId\)\.is\("hidden_at",null\)/);
 assert.match(x,/\.range\(page\*30,page\*30\+30\)/);
 assert.match(x,/rows\.slice\(0,30\)\.reverse\(\)/);
 assert.match(x,/has_older:rows\.length>30/);
 assert.match(thread,/result\.has_older&&page<99/);
});
