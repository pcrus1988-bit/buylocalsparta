/**
 * MERIDIO asset dossier schema v1.
 * Pure validation and serialization of REAL user-entered draft data.
 * Records are never promoted to an asset, entitlement or investment offering.
 * No fake assets, mock members, or in-memory vote/review state.
 */
export const ASSET_WORLDS = Object.freeze([
  "real_estate","hospitality","mobility","energy","agriculture",
  "equipment","culture","sport_leisure","land","infrastructure"
]);

export const EVIDENCE_CATEGORIES = Object.freeze([
  "control_document","operating_permissions","insurance","utilization_terms",
  "risk_disclosure","governance_terms"
]);

export const DOSSIER_VERSION = "meridio-asset-dossier/v1";

const LIMITS = Object.freeze({
  assetName: 140,
  location: 240,
  country: 2,
  legalEntity: 180,
  intendedUse: 2000,
  custodyNotes: 1200
});

function plainString(value, max, label, required = true) {
  if (typeof value !== "string") throw new TypeError(label + " must be text");
  const trimmed = value.trim();
  if ((required && !trimmed) || trimmed.length > max || /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/.test(trimmed))
    throw new Error(label + " is missing, too long, or contains control characters");
  return trimmed;
}

export function validateDossierFields(source) {
  if (!source || typeof source !== "object" || Array.isArray(source))
    throw new TypeError("Dossier fields must be an object");
  const category = plainString(source.world, 25, "Asset category");
  if (!ASSET_WORLDS.includes(category)) throw new Error("Choose a recognized asset category");
  const country = plainString(source.country, LIMITS.country, "Country").toUpperCase();
  if (!/^[A-Z]{2}$/.test(country)) throw new Error("Country must be a two-letter ISO code");
  const evidence = source.evidence ?? [];
  if (!Array.isArray(evidence) || evidence.length > EVIDENCE_CATEGORIES.length ||
      evidence.some((kind) => !EVIDENCE_CATEGORIES.includes(kind)) ||
      new Set(evidence).size !== evidence.length)
    throw new Error("Invalid document checklist");
  return {
    assetName: plainString(source.assetName, LIMITS.assetName, "Asset name"),
    world: category,
    location: plainString(source.location, LIMITS.location, "Asset location"),
    country,
    legalEntity: plainString(source.legalEntity, LIMITS.legalEntity, "Legal asset controller"),
    intendedUse: plainString(source.intendedUse, LIMITS.intendedUse, "Intended utilization"),
    custodyNotes: plainString(source.custodyNotes ?? "", LIMITS.custodyNotes, "Additional notes", false),
    evidence: [...evidence]
  };
}

export function createAssetDossier(fields, { id, generatedAt } = {}) {
  const data = validateDossierFields(fields);
  if (typeof id !== "string" || !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(id))
    throw new Error("A random UUID generated by the browser is required");
  const date = new Date(generatedAt);
  if (!Number.isFinite(date.getTime())) throw new Error("A valid export timestamp is required");
  return {
    schema: DOSSIER_VERSION,
    id,
    state: "draft",
    generatedAt: date.toISOString(),
    ...data,
    acknowledgement: "Self-declared draft; not verified, offered, owned or accepted by MERIDIO."
  };
}

export function parseDossier(text) {
  if (typeof text !== "string" || text.length > 100000) throw new Error("The file must be a small JSON text document");
  let value;
  try { value = JSON.parse(text); } catch { throw new Error("The file is not valid JSON"); }
  if (!value || value.schema !== DOSSIER_VERSION || value.state !== "draft")
    throw new Error("Unsupported dossier version or record status");
  const normalized = validateDossierFields(value);
  if (value.acknowledgement !== "Self-declared draft; not verified, offered, owned or accepted by MERIDIO.")
    throw new Error("Unrecognized dossier acknowledgement");
  if (typeof value.id !== "string" || !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(value.id))
    throw new Error("Invalid dossier ID");
  if (typeof value.generatedAt !== "string" || !Number.isFinite(new Date(value.generatedAt).getTime()))
    throw new Error("Invalid dossier timestamp");
  return { ...value, ...normalized };
}

export function dossierReadiness(dossier) {
  const data = validateDossierFields(dossier);
  const outstanding = EVIDENCE_CATEGORIES.filter((kind) => !data.evidence.includes(kind));
  return {
    acknowledgedCategories: [...data.evidence],
    missingCategories: outstanding,
    evidenceVerified: false,
    eligibleForPublication: false,
    // Self-declared checklist ticks are never an approval or a verified document.
    description: "Draft completeness only. Actual supporting files and legal verification have not been performed."
  };
}
