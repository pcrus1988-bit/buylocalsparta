INSERT INTO category_product_types(category_id,product_type_id,is_default,sort_order)
SELECT c.id,pt.id,true,0
FROM _category_type_seed s
JOIN categories c ON c.code=s.category_code AND c.active=true AND c.assignable=true AND c.taxonomy_role='product_class'
JOIN product_types pt ON pt.code=s.product_type_code AND pt.status='active'
ON CONFLICT (category_id,product_type_id) DO UPDATE SET is_default=true,sort_order=0;
